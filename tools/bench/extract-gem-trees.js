'use strict';
// Extract the COMPLETE gem-tree definition from the live cifi-tools bundle.
//
// Each tree carries three things a gem planner needs and which we had nowhere:
//   qualityCosts[]  the tree's own level-up costs
//   gemNodes[]  per-node cost, plus an `unlockRequirement` like "exodus-5" -- nodes are gated
//               by OTHER trees, which is the cross-tree prereq structure
//   upgrades[]  the per-node bonuses, each with `unlock: <level of THIS tree>`, baseCost,
//               costMultiplier and maxLevel
//
// It also recovers the id map (planner id -> sim param suffix, e.g. borge-loot-bonus ->
// attraction_lootBorge), which is what resolves the "level-only" gates: their tree is implied
// by which tree's `upgrades` array they live in.
//
//   node tools/bench/extract-gem-trees.js <live-bundle.js> [--write]

const fs = require('fs');
const path = require('path');

const bundlePath = process.argv[2];
if (!bundlePath) { console.error('usage: extract-gem-trees.js <live-bundle.js> [--write]'); process.exit(2); }
const write = process.argv.includes('--write');
const src = fs.readFileSync(bundlePath, 'utf8');
const OUT = path.join(__dirname, '../reference/gem-trees.json');

function spanFrom(start, open, close) {
  let depth = 0; let inStr = false; let esc = false; let q = '';
  for (let i = start; i < src.length; i++) {
    const c = src[i];
    if (esc) { esc = false; continue; }
    if (c === '\\') { esc = true; continue; }
    if (inStr) { if (c === q) inStr = false; continue; }
    if (c === '"' || c === "'" || c === '`') { inStr = true; q = c; continue; }
    if (c === open) depth++;
    else if (c === close) { depth--; if (depth === 0) return src.slice(start, i + 1); }
  }
  return null;
}

/** Evaluate a bare object/array literal from the bundle (numbers like 2e13, !0 booleans). */
function literal(text) {
  // eslint-disable-next-line no-new-func
  return Function(`"use strict";return (${text});`)();
}

// Each tree object contains a `gemNodes:[` array; walk back to the enclosing object.
const trees = {};
let from = 0;
for (;;) {
  const at = src.indexOf('gemNodes:[', from);
  if (at === -1) break;
  from = at + 1;
  let s = at;
  let depth = 0;
  for (let i = at; i > 0; i--) {
    const c = src[i];
    if (c === '}') depth++;
    else if (c === '{') { if (depth === 0) { s = i; break; } depth--; }
  }
  const objText = spanFrom(s, '{', '}');
  if (!objText) continue;
  let obj;
  try { obj = literal(objText); } catch { continue; }
  // A gem tree has an id and its own node list. The per-hunter OVERRIDE tables also contain a
  // `gemNodes` key (a list of override param names) and would otherwise be swept in -- require
  // the id to tell them apart rather than filtering on a name pattern.
  if (!obj || !Array.isArray(obj.gemNodes) || typeof obj.id !== 'string') continue;
  const name = obj.id;
  const key = String(name).toLowerCase();
  if (trees[key]) continue;
  trees[key] = obj;
}

// planner id -> sim param suffix
const idMap = {};
const mapAt = src.indexOf('{"borge-loot-bonus":"attraction_lootBorge"');
if (mapAt !== -1) {
  const text = spanFrom(mapAt, '{', '}');
  try { Object.assign(idMap, literal(text)); } catch { /* leave empty */ }
}

console.log(`${Object.keys(trees).length} gem trees, ${Object.keys(idMap).length} id mappings\n`);
for (const [name, t] of Object.entries(trees)) {
  const levels = (t.qualityCosts || []).length;
  const nodes = (t.gemNodes || []).length;
  const ups = (t.upgrades || []).length;
  const gatedNodes = (t.gemNodes || []).filter((n) => n.unlockRequirement);
  console.log(`  ${name.padEnd(12)} maxLevel ${String(t.maxLevel ?? '?').padStart(2)}, ${levels} level costs, ${nodes} nodes, ${ups} upgrades`
    + (gatedNodes.length ? `  — nodes ${gatedNodes.map((n) => `${n.node}(${n.unlockRequirement})`).join(' ')}` : ''));
}

if (write) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, `${JSON.stringify({
    generatedFrom: path.basename(bundlePath),
    note: 'Generated by tools/bench/extract-gem-trees.js. Do not hand-edit -- regenerate instead.',
    plannerIdToSimParam: idMap,
    trees,
  }, null, 2)}\n`);
  console.log(`\nwrote ${OUT}`);
}
