'use strict';
// Extract EVERY numbered definition family from an AssetRipper scene export.
//
// extract-loopmods.js did this for LM<N> only. The same serialized-MonoBehaviour data holds the
// definitions for most other domains too -- relics, research units, tech upgrades, generators,
// hunter talents and attributes, badges, projects -- under the same "<Prefix><N><Field>" naming.
// One pass gets them all.
//
// This is game data that is in neither the save (which stores only the player's LEVELS) nor the
// IL2CPP dump (which gives field names and offsets, but no values).
//
//   node tools/bench/extract-scene-defs.js <MainSceneNew.unity> [--write]
//
// See tools/il2cpp-cli/README.md for how to produce the scene. The scene is ~177 MB, so this
// streams it.

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const scenePath = process.argv[2];
if (!scenePath) { console.error('usage: extract-scene-defs.js <scene.unity> [--write]'); process.exit(2); }
const write = process.argv.includes('--write');
const OUT = path.join(__dirname, '../reference/scene-defs.json');

// Prefixes worth keeping. Deliberately an allow-list: the scene is full of numbered UI wiring
// (Button17Icon and friends) and hoovering up everything would bury the real data.
const PREFIXES = [
  'Relic', 'RU', 'SU', 'TU', 'TUQ', 'ATU', 'UDU', 'MK', 'Project', 'Badge',
  'BorgeSkill', 'OzzySkill', 'KnoxSkill', 'VexinSkill', 'POM', 'POI', 'POK', 'DU', 'IS',
];
// Only fields that describe the upgrade itself. Everything else on these objects is UI wiring
// (object references), which carries no information about game balance.
const DATA_FIELD = /^(StartCost|Cost|CostExponent|CostGrowthExponent|AdditiveCostIncrease|Bonus|BonusExponent|BonusInt|MaxLevel|MaxLevelPreOuro|MaxLevelPostOuro|Level|Available|Unlocked|Multiplier|Effect|Value)\d*$/;

const prefixAlt = PREFIXES.slice().sort((a, b) => b.length - a.length).join('|');
const FIELD = new RegExp(`^\\s{2}(${prefixAlt})(\\d+)([A-Za-z0-9]+):\\s*(-?[\\d.]+(?:[eE][-+]?\\d+)?)\\s*$`);
const FIELD_OPEN = new RegExp(`^\\s{2}(${prefixAlt})(\\d+)([A-Za-z0-9]+):\\s*$`);
const SUBFIELD = /^\s{4}(mantissa|exponent):\s*(-?[\d.]+(?:[eE][-+]?\d+)?)\s*$/;

const families = new Map(); // prefix -> Map(index -> record)

function put(prefix, idx, field, value) {
  if (!DATA_FIELD.test(field)) return;
  if (!families.has(prefix)) families.set(prefix, new Map());
  const fam = families.get(prefix);
  if (!fam.has(idx)) fam.set(idx, {});
  fam.get(idx)[field] = value;
}

let pending = null;
const rl = readline.createInterface({ input: fs.createReadStream(scenePath), crlfDelay: Infinity });

rl.on('line', (line) => {
  if (pending) {
    const sub = SUBFIELD.exec(line);
    if (sub) {
      pending.parts[sub[1]] = Number(sub[2]);
      if ('mantissa' in pending.parts && 'exponent' in pending.parts) {
        // Costs run past 10^6000, so the exponent is the usable value, not the product.
        put(pending.prefix, pending.idx, pending.field, { mantissa: pending.parts.mantissa, exponent: pending.parts.exponent });
        put(pending.prefix, pending.idx, `${pending.field}E`, pending.parts.exponent);
        pending = null;
      }
      return;
    }
    pending = null;
  }

  const m = FIELD.exec(line);
  if (m) {
    const value = Number(m[4]);
    if (Number.isFinite(value)) put(m[1], Number(m[2]), m[3], value);
    return;
  }
  const open = FIELD_OPEN.exec(line);
  if (open) pending = { prefix: open[1], idx: Number(open[2]), field: open[3], parts: {} };
});

rl.on('close', () => {
  const out = {};
  console.log('family        entries  fields seen');
  for (const [prefix, fam] of [...families.entries()].sort((a, b) => b[1].size - a[1].size)) {
    const obj = Object.fromEntries([...fam.entries()].sort((a, b) => a[0] - b[0]));
    // Drop families where nothing but Level survived -- that is UI state, not a definition.
    const informative = Object.values(obj).some((r) => Object.keys(r).some((k) => k !== 'Level' && k !== 'Available'));
    if (!informative) continue;
    out[prefix] = obj;
    const fields = new Set();
    for (const r of Object.values(obj)) for (const k of Object.keys(r)) fields.add(k);
    console.log(`  ${prefix.padEnd(12)} ${String(fam.size).padStart(4)}     ${[...fields].slice(0, 8).join(', ')}`);
  }

  if (write) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, `${JSON.stringify({
      generatedFrom: path.basename(scenePath),
      note: 'Generated by tools/bench/extract-scene-defs.js from an AssetRipper Unity-project export. '
        + 'Do not hand-edit -- regenerate. Costs beyond double range are kept as {mantissa, exponent} '
        + 'with the exponent also exposed as <Field>E. Indices are the game\'s own; whether they line '
        + 'up with the save\'s same-named indices is a SEPARATE question per family -- verify before joining.',
      families: out,
    }, null, 1)}\n`);
    console.log(`\nwrote ${OUT}`);
  }
});
